"""Evaluate retrieval quality of the knowledge base.

    python knowledge_base/tools/evaluate.py                 # hybrid (dense + BM25)
    python knowledge_base/tools/evaluate.py --mode lexical  # BM25 only (no fastembed needed)
    python knowledge_base/tools/evaluate.py --report knowledge_base/eval/retrieval_results.md

Metrics per question: hit@1/3/5 (an expected section is retrieved), reciprocal rank, key-fact recall
(share of key facts found in the top-k text), permission leaks (a forbidden document returned) and
no-evidence handling (off-topic questions must return no_relevant_evidence).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kb_lib import KB_ROOT, KnowledgeBase  # noqa: E402

EVAL_FILE = KB_ROOT / "eval" / "rag_eval_set.jsonl"


def matches(result: dict, ref: str) -> bool:
    doc, _, sec = ref.partition(" §")
    return result["document_id"] == doc and (str(result["section"]) == sec or str(result["section"]).startswith(sec + "."))


def evaluate(kb: KnowledgeBase, k: int = 5) -> tuple[list[dict], dict]:
    rows = []
    for line in EVAL_FILE.read_text().splitlines():
        q = json.loads(line)
        out = kb.search(q["question"], q["role"], k=k)
        res = out["results"]
        ranks = [i + 1 for i, r in enumerate(res) if any(matches(r, e) for e in q["expected_sections"])]
        context = "\n".join(r["text"] for r in res).lower()
        facts = [f for f in q["key_facts"] if f.lower() in context]
        leak = [r["document_id"] for r in res if r["document_id"] in q["must_not_return"]]
        row = {"id": q["id"], "set": q["set"], "type": q["type"], "role": q["role"], "question": q["question"],
               "status": out["status"], "best_dense": out["best_dense_score"],
               "top": [r["citation"] for r in res[:3]], "first_hit_rank": ranks[0] if ranks else None,
               "fact_recall": (len(facts) / len(q["key_facts"])) if q["key_facts"] else None,
               "missing_facts": [f for f in q["key_facts"] if f not in facts], "leaks": leak}
        if q["set"] == "no_evidence":
            row["passed"] = out["status"] == "no_relevant_evidence"
        elif q["set"] == "permission" and not q["expected_sections"]:
            row["passed"] = not leak
        else:
            row["passed"] = bool(ranks) and ranks[0] <= 3 and not leak and (row["fact_recall"] in (None, 1.0))
        rows.append(row)
    ans = [r for r in rows if r["set"] in ("core", "extended", "permission") and r["id"] != "P04"]
    def rate(rs, f):
        return round(sum(f(r) for r in rs) / len(rs), 3) if rs else None
    summary = {
        "questions": len(rows),
        "hit@1": rate(ans, lambda r: r["first_hit_rank"] == 1),
        "hit@3": rate(ans, lambda r: r["first_hit_rank"] is not None and r["first_hit_rank"] <= 3),
        "hit@5": rate(ans, lambda r: r["first_hit_rank"] is not None),
        "mrr": rate(ans, lambda r: 1 / r["first_hit_rank"] if r["first_hit_rank"] else 0),
        "fact_recall@5": rate([r for r in ans if r["fact_recall"] is not None], lambda r: r["fact_recall"]),
        "permission_leaks": sum(len(r["leaks"]) for r in rows),
        "no_evidence_correct": f"{sum(r['passed'] for r in rows if r['set'] == 'no_evidence')}/{sum(r['set'] == 'no_evidence' for r in rows)}",
        "core_passed": f"{sum(r['passed'] for r in rows if r['set'] == 'core')}/{sum(r['set'] == 'core' for r in rows)}",
        "all_passed": f"{sum(r['passed'] for r in rows)}/{len(rows)}",
    }
    return rows, summary


def report(rows, summary, mode) -> str:
    out = [f"# Retrieval evaluation ({mode})", "",
           "Generated by `knowledge_base/tools/evaluate.py`. A question passes when an expected section is in the top 3, "
           "every key fact appears in the top-5 retrieved text, and no forbidden document is returned. "
           "Off-topic questions pass when retrieval returns `no_relevant_evidence`.", "",
           "| Metric | Value |", "|---|---|"] + [f"| {k} | {v} |" for k, v in summary.items()] + ["",
           "| ID | Set | Role | Question | First hit rank | Fact recall | Passed | Top citation |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        top = r["top"][0] if r["top"] else r["status"]
        fr = "-" if r["fact_recall"] is None else f"{r['fact_recall']:.0%}"
        out.append(f"| {r['id']} | {r['set']} | {r['role']} | {r['question']} | {r['first_hit_rank'] or '-'} | {fr} | "
                   f"{'yes' if r['passed'] else '**no**'} | {top} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mode", choices=["hybrid", "lexical"], default="hybrid")
    ap.add_argument("-k", type=int, default=5)
    ap.add_argument("--report", type=Path)
    ap.add_argument("--verbose", action="store_true")
    a = ap.parse_args()
    kb = KnowledgeBase(use_dense=a.mode == "hybrid")
    rows, summary = evaluate(kb, a.k)
    for r in rows:
        if a.verbose or not r["passed"]:
            print(f"{'PASS' if r['passed'] else 'FAIL'} {r['id']} [{r['role']}] {r['question'][:70]}\n"
                  f"     status={r['status']} first_hit={r['first_hit_rank']} best_dense={r['best_dense']} "
                  f"missing={r['missing_facts']} leaks={r['leaks']}\n     top={r['top']}")
    print(json.dumps(summary, indent=1))
    if a.report:
        a.report.write_text(report(rows, summary, a.mode))
